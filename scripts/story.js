export async function ensureStoryJournal(force = false) {
  if (!game.users.activeGM?.isSelf) return;
  let j = game.journal.getName(NAME);
  if (j && !force && (j.getFlag(MOD, "storyVer") ?? 0) >= VER) return j;
  const pages = PAGES.map(([name, content], i) => ({ name, type: "text", sort: (i + 1) * 100, text: { content } }));
  if (j) { await j.deleteEmbeddedDocuments("JournalEntryPage", j.pages.map((p) => p.id)); await j.createEmbeddedDocuments("JournalEntryPage", pages); }
  else {
    const jf = game.folders.find((f) => f.name === "Arkane 1920s" && f.type === "JournalEntry");
    j = await JournalEntry.create({ name: NAME, folder: jf?.id, ownership: { default: 0 }, pages });
  }
  await j.setFlag(MOD, "storyVer", VER);
  return j;
}
