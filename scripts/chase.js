const box = (x, y, w, h) => [[x, y, x + w, y], [x + w, y, x + w, y + h], [x + w, y + h, x, y + h], [x, y + h, x, y]].map((c) => ({ c: c.map((n) => Math.round(n * G)) }));
function walls() {
  const w = [];
  const line = (...c) => w.push({ c });
  // building fronts (y 400 north, y 1800 south) with side-street gaps, dead-end side streets
  for (const [a, b] of [[0, 1900], [2300, 4700], [5000, 8000]]) line(a, 400, b, 400);
  for (const x of [1900, 2300, 4700, 5000]) line(x, 0, x, 400);
  for (const [a, b] of [[0, 1900], [2300, 6100], [6500, 8000]]) line(a, 1800, b, 1800);
  for (const x of [1900, 2300, 6100, 6500]) line(x, 1800, x, 2200);
  // road obstacles (x, y, w, h in squares)
  const obs = [[14, 7, 2, 2], [28, 10, 5, 3], [36, 13, 8, 2], [56, 6, 2, 2], [57, 14, 2, 2], [10, 5, 3, 2], [20, 5, 3, 2], [22, 14, 3, 2], [51, 15, 3, 2], [64, 15, 3, 2], [70, 5, 3, 2], [4, 15, 3, 2],
    [47, 5, 1, 5], [47, 14, 1, 3]];
  for (const [x, y, ww, hh] of obs) w.push(...box(x, y, ww, hh));
  // hospital fence + gate pillars (the gate gap is y 900-1300)
  w.push({ c: [7700, 400, 7700, 880], ...NOMOVE }, { c: [7700, 1320, 7700, 1800], ...NOMOVE });
  w.push(...box(76.76, 8.4, 0.56, 0.64), ...box(76.76, 12.9, 0.56, 0.64));
  return w.map((x) => ({ ...x, flags: { [MOD]: { chase: 1 } } }));
}
