// npm run fx -- <JB2A folder (the one that contains Library/)> [--prefix modules/JB2A_DnD5e/] [--also "Spell One,Spell Two"]
// Looks in Library/<Level>/<Spell>/ of your JB2A copy, matches each spell folder to a spell of ours BY NAME, and writes
// src/data/spellFx.generated.ts (which files can be that spell's effect). Nothing is guessed: only files you really have.
// Our spells = every `name: "..."` in src/data/spells/*.ts + every S("...") in scripts/spells.js (+ --also). It also lists the ones with no match.
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, "");
const slugOf = (n) => String(n).trim().toLowerCase().replace(/['\u2019\u2018`]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const FX = /\.(webm|webp)$/i;

function walk(dir, out = []) {
  for (const d of readdirSync(dir)) { const p = join(dir, d); statSync(p).isDirectory() ? walk(p, out) : out.push(p); }
  return out;
}

// names of our spells
export function spellNames(also = []) {
  const names = new Set(also);
  const grab = (file, rx) => { if (existsSync(file)) for (const m of readFileSync(file, "utf8").matchAll(rx)) names.add(m[1]); };
  if (existsSync("src/data/spells")) for (const f of readdirSync("src/data/spells")) if (f.endsWith(".ts")) grab(join("src/data/spells", f), /\bname: "([^"]+)"/g);
  grab("scripts/spells.js", /\bS\("([^"]+)"/g);
  return [...names];
}

// files: paths like "Library/Cantrip/Fire_Bolt/FireBolt_01_Regular_Orange_05ft_600x400.webm" ("/" separated, relative to the JB2A folder)
export function buildManifest(files, names, prefix) {
  const byFolder = new Map(names.map((n) => [norm(n), slugOf(n)]));
  const out = {}, hit = new Set();
  for (const f of files) {
    const parts = f.split("/"), i = parts.indexOf("Library");
    if (i < 0 || parts.length < i + 4 || !FX.test(f) || /thumb/i.test(parts.at(-1))) continue;      // Library/<Level>/<Spell>/.../file
    const id = byFolder.get(norm(parts[i + 2]));
    if (!id) continue;
    hit.add(id);
    // family = the sub-folders + file name without the range (05ft) and the size (600x400): one effect in one colour
    const stem = parts.slice(i + 3).join("_").replace(FX, "").replace(/_\d+ft(?=_|$)/gi, "").replace(/_\d+x\d+$/i, "").toLowerCase();
    ((out[id] ??= {})[stem] ??= []).push(prefix + f);
  }
  for (const id of Object.keys(out)) for (const k of Object.keys(out[id])) out[id][k].sort();
  const sorted = Object.fromEntries(Object.keys(out).sort().map((id) => [id, Object.fromEntries(Object.entries(out[id]).sort())]));
  return { manifest: sorted, missing: [...new Set(names.map(slugOf))].filter((s) => !hit.has(s)).sort() };
}

if (resolve(process.argv[1] ?? "") === resolve(fileURLToPath(import.meta.url))) {
  const args = process.argv.slice(2), opt = (k) => { const i = args.indexOf(k); return i >= 0 ? args.splice(i, 2)[1] : undefined; };
  const prefix = opt("--prefix") ?? "modules/JB2A_DnD5e/", also = (opt("--also") ?? "").split(",").map((s) => s.trim()).filter(Boolean);
  const dir = resolve(args[0] ?? "dev/fx");
  if (!existsSync(dir)) { console.error(`ไม่เจอโฟลเดอร์ ${dir}\nใช้: npm run fx -- <โฟลเดอร์ JB2A ที่มี Library/ อยู่ข้างใน>`); process.exit(1); }
  const files = walk(dir).map((p) => p.slice(dir.length + 1).split(/[\\/]/).join("/"));
  if (!files.some((f) => f.split("/").includes("Library"))) { console.error(`ใน ${dir} ไม่มีโฟลเดอร์ Library/ (ต้องเป็นโครงเดิมของ JB2A: Library/Cantrip/Fire_Bolt/...)`); process.exit(1); }
  const names = spellNames(also), { manifest, missing } = buildManifest(files, names, prefix);
  const out = "src/data/spellFx.generated.ts";
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `// generated by tools/scan-fx.mjs (npm run fx): do not edit by hand\nimport type { FxManifest } from "../spells/fxAuto";\n\nexport const FX_MANIFEST: FxManifest = ${JSON.stringify(manifest, null, 1)};\n`);
  const n = Object.values(manifest).reduce((a, e) => a + Object.values(e).reduce((b, l) => b + l.length, 0), 0);
  console.log(`${out}: ${Object.keys(manifest).length} สกิลเจอเอฟเฟกต์ ${n} ไฟล์ (prefix ${prefix})`);
  if (missing.length) console.log(`ไม่เจอใน JB2A นี้ (${missing.length}): ${missing.join(", ")}\n  → ชื่อโฟลเดอร์อาจต่าง หรือไม่มีในของฟรี ใส่ { seq } / { file } ของเองในสกิล หรือเพิ่มด้วย --also`);
}
