// npm run icons [-- <spells folder> [url prefix]]
// Scans the spell icon folder and writes src/data/spellIcons.generated.ts (which file is whose icon). Run it after adding pictures.
// Two folder layouts are understood, even mixed:
//   spells/<spell>/_default.webp , spells/<spell>/<character>.webp        (by spell: the layout we recommend)
//   spells/<character>/<character>-<spell>.webp                           (by character: the layout already in use)
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const IMG = /\.(webp|png|jpe?g|svg)$/i;
const key = (s) => s.toLowerCase();

// files: paths like "vivian/vivian-fire-bolt.webp" (relative to the spells folder, "/" separated)
export function buildManifest(files, prefix) {
  const out = {};
  const put = (spell, caster, path) => {
    const e = (out[spell] ??= {});
    if (caster) (e.byCaster ??= {})[caster] = prefix + path; else e.default = prefix + path;
  };
  for (const f of files) {
    const parts = f.split("/");
    if (parts.length !== 2 || !IMG.test(f)) continue;
    const dir = key(parts[0]), stem = key(parts[1].replace(IMG, ""));
    if (stem.startsWith(dir + "-")) put(stem.slice(dir.length + 1), dir, f);   // by character
    else put(dir, stem === "_default" ? null : stem, f);                          // by spell
  }
  const sorted = {};
  for (const id of Object.keys(out).sort()) {
    const e = out[id];
    sorted[id] = { ...(e.default ? { default: e.default } : {}), ...(e.byCaster ? { byCaster: Object.fromEntries(Object.entries(e.byCaster).sort()) } : {}) };
  }
  return sorted;
}

export function render(manifest) {
  return `// generated by tools/scan-icons.mjs (npm run icons): do not edit by hand\nimport type { IconManifest } from "../spells/types";\n\nexport const ICON_MANIFEST: IconManifest = ${JSON.stringify(manifest, null, 2)};\n`;
}

function walk(root) {
  const files = [];
  for (const d of readdirSync(root)) {
    const p = join(root, d);
    if (!statSync(p).isDirectory()) continue;
    for (const f of readdirSync(p)) if (statSync(join(p, f)).isFile()) files.push(`${d}/${f}`);
  }
  return files;
}

if (resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1] ?? "")) {
  const dir = resolve(process.argv[2] ?? "spells");
  const id = JSON.parse(readFileSync("module.json", "utf8")).id;
  const prefix = process.argv[3] ?? `modules/${id}/spells/`;
  if (!existsSync(dir)) { console.error(`ไม่เจอโฟลเดอร์ ${dir}\nใช้: npm run icons -- <โฟลเดอร์ spells> [url prefix]`); process.exit(1); }
  const manifest = buildManifest(walk(dir), prefix);
  const out = "src/data/spellIcons.generated.ts";
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, render(manifest));
  const n = Object.values(manifest).reduce((a, e) => a + (e.default ? 1 : 0) + Object.keys(e.byCaster ?? {}).length, 0);
  console.log(`${out}: ${Object.keys(manifest).length} สกิล, ${n} ไฟล์ (prefix ${prefix})`);
}
